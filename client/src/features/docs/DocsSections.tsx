/** Награда за место в особом событии — зеркало SPECIAL_PLACE_REWARDS сервера. */
const SPECIAL_PLACE_REWARDS: Array<[place: number, influence: number, experience: number]> = [
  [1, 14, 450],
  [2, 12, 400],
  [3, 10, 350],
  [4, 8, 300],
  [5, 7, 250],
  [6, 6, 200],
  [7, 5, 150],
  [8, 4, 100],
];

const DIFFICULTY_TITLE: Record<string, string> = {
  easy: 'Лёгкий',
  medium: 'Средний',
  hard: 'Сложный',
  core: 'Ядро',
};

const DIFFICULTY_ORDER = ['easy', 'medium', 'hard', 'core'];

/** Награды сектора берём с сервера — вики не расходится с балансом смены. */
function useDifficulties(): Difficulty[] {
  const [rows, setRows] = useState<Difficulty[]>([]);
  useEffect(() => {
    getDifficulties()
      .then((list) =>
        setRows(
          [...list].sort(
            (a, b) => DIFFICULTY_ORDER.indexOf(a.slug) - DIFFICULTY_ORDER.indexOf(b.slug),
          ),
        ),
      )
      .catch(() => setRows([]));
  }, []);
  return rows;
}

function SectorRewards() {
  const difficulties = useDifficulties();
  if (difficulties.length === 0) return null;

  return (
    <Table
      head={['Сектор', 'Влияние', 'Опыт', 'За укрепление']}
      rows={difficulties.map((d) => [
        DIFFICULTY_TITLE[d.slug] ?? d.name,
        `${d.influence_reward}`,
        `${d.experience_reward}`,
        `+${Math.floor(d.influence_reward / 2)} / +${Math.floor(d.experience_reward / 2)}`,
      ])}
    />
  );
}

