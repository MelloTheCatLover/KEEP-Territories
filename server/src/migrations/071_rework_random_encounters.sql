-- Полная переработка случайных встреч.
--
-- 1) Пул = 100 встреч: 1–50 негативные (забирают), 51–100 позитивные (дают).
--    У каждой встречи есть эффект на ВСЕХ ветках — «ничего не произошло» больше
--    не бывает. Правила и балансировка живут в services/encounter-catalog.ts,
--    здесь только строки пула (номер, заголовок, полярность).
-- 2) Прежние «свопы по капитану» (16, 20–24) заменены на проверки по составу:
--    отдельный вид строк kind = 'roster', по одной на команду сезона, с
--    привязкой к конкретному ребёнку-победителю/МВП (target_child_id).
--    Их создаёт encounter.service.syncRosterChecks() под номерами 901+.
-- 3) Обнуления характеристик теперь сжигают очки апгрейда (см. encounter.service),
--    поэтому «обнулить» действительно означает потерю, а не возврат очков.

ALTER TABLE random_encounters
  ADD COLUMN kind VARCHAR(20) NOT NULL DEFAULT 'standard'
    CHECK (kind IN ('standard', 'roster')),
  ADD COLUMN polarity VARCHAR(10) NOT NULL DEFAULT 'positive'
    CHECK (polarity IN ('positive', 'negative')),
  ADD COLUMN target_child_id UUID REFERENCES children(id) ON DELETE SET NULL,
  ADD COLUMN roster_stat VARCHAR(20)
    CHECK (roster_stat IS NULL OR roster_stat IN
      ('strength', 'intelligence', 'endurance', 'leadership', 'luck'));

-- Привязки старых свопов больше не действуют.
UPDATE random_encounters SET target_team_id = NULL;

